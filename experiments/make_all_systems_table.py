#!/usr/bin/env python3
"""Regenerate the per-system federated table from the 3-seed, 50-round run.

The block previously in the paper was transcribed from a 2-seed, 8-round run.
Eight rounds is short of convergence for these probes, and the ordering it
produced does not survive: at mild skew the text branch overtakes fusion once
the runs are trained out. Generating the table from the JSON keeps the printed
numbers tied to the run that produced them.
"""

from __future__ import annotations

import json
import statistics as st
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "tea_results" / "federated_all_systems_full"
       / "federated_all_systems.json")
OUT = ROOT / "experiments" / "all_systems_block.tex"
BS = chr(92)

ROWS = [("text_distilbert", "Text (frozen DistilBERT)"),
        ("image_vit_tiny", "Image (frozen ViT-tiny)"),
        ("vit_distilbert", "ViT$+$DistilBERT fusion")]


def main() -> None:
    d = json.load(open(SRC, encoding="utf-8"))
    meta = d["_meta"]
    seeds = sorted({r["seed"] for r in d["runs"].values()})
    fed, loc, byK = defaultdict(list), defaultdict(list), defaultdict(list)
    for r in d["runs"].values():
        fed[(r["system"], r["alpha"])].append(r["fedavg_final_macro_f1"])
        loc[(r["system"], r["alpha"])].append(r["local_only_mean_macro_f1"])
        if r["alpha"] == 1.0:
            byK[(r["system"], r["num_clients"])].append(r["fedavg_final_macro_f1"])
    alphas = sorted({a for _, a in fed})
    best = {a: max(st.mean(fed[(s, a)]) for s, _ in ROWS) for a in alphas}

    L = [BS + "begin{table}[t]",
         BS + "caption{Federated adaptation across the paper's systems, not only "
         "ResNet$+$compact. Frozen encoders with SGD-trained heads on the shared "
         "source-grouped split; within a cell every system trains on the "
         "identical client partition. Entries are means of "
         + str(len(seeds)) + " seeds over " + str(meta["rounds"]) + " rounds and "
         "all client counts, so each is an average of " + str(len(fed[(ROWS[0][0], alphas[0])]))
         + " runs; \\emph{Local} is the no-communication control. Fusion leads "
         "under strong label skew, while the text branch leads at mild skew --- "
         "the ordering depends on the skew and is reported, not ranked.}",
         BS + "label{tab:all_systems_fed}",
         BS + "centering" + BS + "footnotesize",
         BS + "setlength" + BS + "tabcolsep{4.0pt}",
         BS + "begin{tabular}{lcccc}",
         BS + "toprule",
         "& " + " & ".join(BS + "multicolumn{2}{c}{$" + BS + "alpha=" + f"{a:g}$" + "}"
                           for a in alphas) + BS + BS,
         BS + "cmidrule(lr){2-3}" + BS + "cmidrule(lr){4-5}",
         "System & " + " & ".join("FedAvg & Local" for _ in alphas) + BS + BS,
         BS + "midrule"]
    for key, label in ROWS:
        cells = []
        for a in alphas:
            f = st.mean(fed[(key, a)])
            v = f"{f:.3f}"
            if abs(f - best[a]) < 1e-9:
                v = BS + "textbf{" + v + "}"
            cells += [v, f"{st.mean(loc[(key, a)]):.3f}"]
        L.append(f"{label} & " + " & ".join(cells) + BS + BS)
    # the warm-start ResNet+compact core is federated by a different script
    # and over a different client range; kept as a footer row, not a peer row
    L.append(BS + "midrule")
    L.append("ResNet$+$compact (warm) & " + BS
             + "multicolumn{4}{c}{0.892--0.910 over 2--8 clients}" + BS + BS)
    L += [BS + "bottomrule", BS + "end{tabular}", BS + "end{table}"]

    body = ("%% generated by experiments/make_all_systems_table.py "
            "-- do not hand-edit\n\n" + "\n".join(L) + "\n")
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT}")
    for key, label in ROWS:
        line = "  " + f"{label:<26}"
        for a in alphas:
            line += f" a={a:g}: {st.mean(fed[(key, a)]):.3f} (local {st.mean(loc[(key, a)]):.3f})"
        print(line)
    print("\n  alpha=1 FedAvg by client count")
    Ks = sorted({k for _, k in byK})
    print("    " + "system".ljust(24) + "".join(f"K={K:<6}" for K in Ks))
    for key, label in ROWS:
        print("    " + key.ljust(24)
              + "".join(f"{st.mean(byK[(key, K)]):<8.3f}" for K in Ks))


if __name__ == "__main__":
    main()
