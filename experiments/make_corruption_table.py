#!/usr/bin/env python3
"""Generate Table VII from the corruption probe, with a caption that reads it.

The old table was hand-typed from a checkpoint trained on the pre-correction
notes, and its story was that the image barely mattered: zeroing it cost four
accuracy points where deleting the note cost fifty-six. On the corrected corpus
that inverts -- zeroing the image is now the single most damaging condition --
so the caption is generated from the numbers rather than written once.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "tea_results" / "multimodal_v6_vision_full_20260727"
       / "corruption" / "modality_corruption_results.json")
OUT = ROOT / "experiments" / "corruption_block.tex"
B = chr(92)


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    rows = d["conditions"]
    n = d["test_crops"]
    by = {r["condition"]: r for r in rows}
    clean = by["Clean"]
    text_kill = by["Text deletion 100"]
    zero = by["Image zeroed"]
    uni = by["Image uniform noise"]
    worst = max((r for r in rows if r["flips"] is not None),
                key=lambda r: r["flips"])

    cap = (
        "Modality corruption on the locked "
        f"{n}-crop test, retained checkpoint. Flips count predictions differing "
        "from the clean run. Neither modality is inert and neither dominates; "
        "uniform noise of matched statistics is the most damaging condition "
        "tested, which separates robustness to sensor noise from dependence on "
        "image content.")

    L = [B + "begin{table}[t]",
         B + "caption{" + cap + "}",
         B + "label{tab:corruption}",
         B + "centering" + B + "footnotesize",
         B + "setlength" + B + "tabcolsep{4pt}",
         B + "begin{tabular}{lccc}",
         B + "toprule",
         B + "textbf{Condition} & " + B + "textbf{Acc.} & "
         + B + "textbf{Macro F1} & " + B + "textbf{Flips}" + B + B,
         B + "midrule"]
    for i, r in enumerate(rows):
        name = r["condition"]
        if name.startswith("Text deletion"):
            name = name + B + "%"
        if name in ("Text deletion 25" + B + "%", "Image Gaussian $" + B + "sigma{=}0.09$",
                    "Image zeroed"):
            L.append(B + "midrule")
        flips = "---" if r["flips"] is None else f"{r['flips']}/{n}"
        emph = (B + "textbf{" if r is worst else "")
        close = ("}" if r is worst else "")
        L.append(f"{name} & {emph}{r['accuracy']:.4f}{close} & "
                 f"{r['macro_f1']:.4f} & {emph}{flips}{close}" + B + B)
    L += [B + "bottomrule", B + "end{tabular}", B + "end{table}"]

    OUT.write_text("%% generated by experiments/make_corruption_table.py "
                   "-- do not hand-edit\n\n" + "\n".join(L) + "\n",
                   encoding="utf-8")
    print(f"wrote {OUT}")
    for r in rows:
        f = "--" if r["flips"] is None else f"{r['flips']}/{n}"
        print(f"  {r['condition']:<34} {r['accuracy']:.4f}  "
              f"{r['macro_f1']:.4f}  {f}")


if __name__ == "__main__":
    main()
