#!/usr/bin/env python3
"""Generate Table VI from the reruns, instead of leaving it hand-transcribed.

Table VI was the last live table still typed into main.tex by hand, which is why
it survived the note correction carrying July numbers. Its five rows come from
two files:

  modality_hierarchy_results.json   text-only, image-only, unrouted fusion and
                                    the routed proposal, on validation and on
                                    the locked test
  encoder_selection_results.json    the frozen ViT-tiny + DistilBERT candidate

Row mapping is by role, not by key name, because the two files name the same
system differently. Validation `fusion` and test `text_image_fusion` are the
unrouted VLM; validation `proposed` and test `proposed_multimodal` are the
routed one. The ordering that identifies them survives the corpus change --
the routed system is above the unrouted on validation in both the old run
(0.8919 against 0.8378) and the new one -- and the script asserts it, so a
future rerun that inverts the roles fails here rather than silently relabelling
a row. Validation `raw_cross_attention` has no test counterpart and is a
validation-only diagnostic, so it is not a row.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HIER = (ROOT / "tea_results" / "multimodal_v6_vision_full_20260727"
        / "modality_hierarchy" / "modality_hierarchy_results.json")
SEL = (ROOT / "tea_results" / "vit_lm_encoder_selection_20260729"
       / "encoder_selection_results.json")
OUT = ROOT / "experiments" / "encoder_selection_block.tex"
B = chr(92)


def main() -> None:
    h = json.loads(HIER.read_text(encoding="utf-8"))
    s = json.loads(SEL.read_text(encoding="utf-8"))
    v, t = h["selected_validation"], h["fixed_test"]
    keep = v["keep_rate"]

    assert v["proposed"]["accuracy"] >= v["fusion"]["accuracy"], (
        "routed no longer leads unrouted on validation; the row mapping in this "
        "script identifies them by that ordering and must be revisited")

    cand, inc = s["candidate"], s["incumbent"]
    rows = [
        ("Text PLM (DistilBERT)", v["text_only"], t["text_only"]),
        ("Image ViT (ViT-tiny)", v["image_only"], t["image_only"]),
        ("Raw ResNet$+$compact VLM", v["fusion"], t["text_image_fusion"]),
        ("ViT$+$DistilBERT VLM", cand["selected_validation"], cand["fixed_test"]),
        ("Routed ResNet$+$compact", inc["selected_validation"], inc["fixed_test"]),
    ]
    best_val = max(a["accuracy"] for _, a, _ in rows)
    best_acc = max(b["accuracy"] for _, _, b in rows)
    best_f1 = max(b["macro_f1"] for _, _, b in rows)

    winner = "the routed incumbent" if s["winner"].startswith("resnet") \
        else "the ViT$+$DistilBERT candidate"
    cap = (
        "Common-support encoder selection. Architecture choice uses validation "
        "only; test metrics are reported after selection. All rows are scored "
        f"under the deterministic sparse-note mask at {100 * keep:.0f}" + B + "% of note "
        "tokens retained, the rate the routing hierarchy selects. The image row "
        "uses ViT-tiny, not the ViT-Base of Table~" + B + "ref{tab:unimodal_cent_fed}.")

    def bold(x, best):
        t_ = f"{x:.4f}"
        return B + "textbf{" + t_ + "}" if abs(x - best) < 1e-9 else t_

    L = [B + "begin{table}[t]",
         B + "caption{" + cap + "}",
         B + "label{tab:family_comparison}",
         B + "centering" + B + "footnotesize",
         B + "setlength" + B + "tabcolsep{4pt}",
         B + "begin{tabular}{lccc}",
         B + "toprule",
         B + "textbf{Actual system} & " + B + "textbf{Val. acc.} & "
         + B + "textbf{Test acc.} & " + B + "textbf{Test F1}" + B + B,
         B + "midrule"]
    for name, va, te in rows:
        L.append(f"{name} & {bold(va['accuracy'], best_val)} & "
                 f"{bold(te['accuracy'], best_acc)} & "
                 f"{bold(te['macro_f1'], best_f1)}" + B + B)
    L += [B + "bottomrule", B + "end{tabular}", B + "end{table}"]

    OUT.write_text("%% generated by experiments/make_encoder_selection_table.py "
                   "-- do not hand-edit\n\n" + "\n".join(L) + "\n",
                   encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  keep rate {keep:g}")
    for name, va, te in rows:
        print(f"  {name:<28} val {va['accuracy']:.4f}  "
              f"test {te['accuracy']:.4f}  F1 {te['macro_f1']:.4f}")


if __name__ == "__main__":
    main()
