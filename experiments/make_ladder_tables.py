#!/usr/bin/env python3
"""Emit the text and text+image ladder tables as LaTeX, from the result JSON.

Generated rather than transcribed so the numbers cannot drift from the run.
Layout puts note sparsity across the columns, so the flat-then-separating
pattern is readable along a single row.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXT = ROOT / "tea_results" / "text_pipeline_ladder" / "text_pipeline_ladder.json"
MM = ROOT / "tea_results" / "multimodal_pipeline_ladder" / "multimodal_pipeline_ladder.json"
OUT = ROOT / "experiments" / "ladder_tables.tex"

SPARSITIES = ["sparsity=0.0", "sparsity=0.5", "sparsity=0.75"]
BS = chr(92)


def esc(s: str) -> str:
    return s.replace("%", BS + "%").replace("+", "$+$")


def rows_for(path: Path):
    d = json.load(open(path, encoding="utf-8"))
    names = list(d["ladder"][SPARSITIES[0]].keys())
    out = []
    for n in names:
        cells = []
        for sp in SPARSITIES:
            r = d["ladder"][sp][n]
            cells.append((r["test_accuracy"], r["test_macro_f1"]))
        out.append((n, d["ladder"][SPARSITIES[0]][n]["candidates"], cells))
    return out, d["_meta"]


def render(title: str, label: str, caption: str, path: Path) -> str:
    rows, meta = rows_for(path)
    L = [
        BS + "begin{table}[t]",
        BS + "caption{" + caption + "}",
        BS + "label{" + label + "}",
        BS + "centering" + BS + "footnotesize",
        BS + "setlength" + BS + "tabcolsep{2.6pt}",
        BS + "begin{tabular}{lrcccccc}",
        BS + "toprule",
        "& & " + BS + "multicolumn{2}{c}{Complete} & "
        + BS + "multicolumn{2}{c}{50" + BS + "% deleted} & "
        + BS + "multicolumn{2}{c}{75" + BS + "% deleted}" + BS + BS,
        BS + "cmidrule(lr){3-4}" + BS + "cmidrule(lr){5-6}" + BS + "cmidrule(lr){7-8}",
        "System & Cand. & Acc. & F1 & Acc. & F1 & Acc. & F1" + BS + BS,
        BS + "midrule",
    ]
    gate_rows = [r for r in rows if "gate" in r[0].lower()]
    single_rows = [r for r in rows if "gate" not in r[0].lower()]
    # best single test accuracy per sparsity gets bolded
    best = [max(r[2][i][0] for r in single_rows) for i in range(3)]

    def emit(name, cand, cells):
        parts = []
        for i, (acc, f1) in enumerate(cells):
            a = f"{acc:.3f}"
            if abs(acc - best[i]) < 1e-9 and "gate" not in name.lower():
                a = BS + "textbf{" + a + "}"
            parts += [a, f"{f1:.3f}"]
        clean = name.replace(" (not single model)", "")
        return f"{esc(clean)} & {cand} & " + " & ".join(parts) + BS + BS

    for n, c, cells in single_rows:
        L.append(emit(n, c, cells))
    if gate_rows:
        L.append(BS + "midrule")
        L.append(BS + "multicolumn{8}{l}{" + BS
                 + "emph{Per-class gates (not single models)}}" + BS + BS)
        for n, c, cells in gate_rows:
            L.append(emit(n, c, cells))
    L += [BS + "bottomrule", BS + "end{tabular}", BS + "end{table}"]
    return "\n".join(L)


def main() -> None:
    text_cap = (
        "Text pipeline ladder on the common 75-crop support, with the same "
        "column structure as the visual table. \\emph{Cand.} is the number of "
        "validation-fitted configurations. Each rung is repeated at three note "
        "sparsities; deletion is deterministic, so every rung sees the identical "
        "corruption of the identical notes. At complete notes a single-candidate "
        "path already reaches 0.987 accuracy and the ladder is flat, so the "
        "ceiling belongs to the corpus rather than to the pipeline. Bold marks "
        "the best single model per sparsity. This table varies the pipeline for one fixed encoder; Tables~\\ref{tab:unimodal_cent_fed} and~\\ref{tab:multimodal_cent_fed} vary the encoder for one fixed pipeline and add a federated column."
    )
    mm_cap = (
        "Text${+}$image pipeline ladder on the same 75 crops, selected by the "
        "pre-declared validation score $0.65F_{1,\\mathrm{paired}}"
        "+0.35F_{1,\\mathrm{image}}$. Fusion is saturated at complete notes and "
        "separates only once notes degrade. The gate attains the best validation "
        "accuracy at 50\\% deletion (0.932) yet the worst test accuracy (0.747), "
        "so its search over 243 candidates on 74 validation crops does not "
        "transfer. Bold marks the best single model per sparsity. This table varies the pipeline for one fixed encoder; Tables~\\ref{tab:unimodal_cent_fed} and~\\ref{tab:multimodal_cent_fed} vary the encoder for one fixed pipeline and add a federated column."
    )
    body = "%% generated by experiments/make_ladder_tables.py -- do not hand-edit\n\n"
    body += render("text", "tab:text_ladder", text_cap, TEXT) + "\n\n"
    body += render("mm", "tab:mm_ladder", mm_cap, MM) + "\n"
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    print(body[:400])


if __name__ == "__main__":
    main()
